# PlatformIO pre-script: gzips firmware/web/* into lib/web/panel_files.h as byte arrays (cycle 008, R2).
# The panel is part of the firmware image, so one .bin updates both.
import gzip
import os
import re

Import("env")  # noqa: F821 (provided by PlatformIO)

project = env.subst("$PROJECT_DIR")  # noqa: F821
src_dir = os.path.join(project, "web")
out_path = os.path.join(project, "lib", "web", "panel_files.h")

TYPES = {".html": "text/html; charset=utf-8", ".js": "application/javascript", ".css": "text/css", ".svg": "image/svg+xml"}

files = sorted(f for f in os.listdir(src_dir) if os.path.splitext(f)[1] in TYPES)
lines = ["// Generated by scripts/embed_web.py from web/*. Do not edit.", "#pragma once", "#include <stddef.h>", "#include <stdint.h>", ""]
entries = []
total = 0
for name in files:
    with open(os.path.join(src_dir, name), "rb") as f:
        data = gzip.compress(f.read(), 9, mtime=0)
    total += len(data)
    ident = "kPanel_" + re.sub(r"[^0-9A-Za-z]", "_", name)
    lines.append("static const uint8_t %s[] = {%s};" % (ident, ",".join(str(b) for b in data)))
    entries.append((name, TYPES[os.path.splitext(name)[1]], ident, len(data)))
lines.append("")
lines.append("struct PanelFile { const char* path; const char* type; const uint8_t* data; size_t size; };")
lines.append("static const PanelFile kPanelFiles[] = {")
for name, ctype, ident, size in entries:
    path = "/" if name == "index.html" else "/" + name
    lines.append('    {"%s", "%s", %s, %d},' % (path, ctype, ident, size))
lines.append("};")
lines.append("static const size_t kPanelFileCount = %d;" % len(entries))
text = "\n".join(lines) + "\n"
if total > 150 * 1024:
    raise Exception("panel is %d bytes gzipped, the limit is 150 KB" % total)
if not os.path.exists(out_path) or open(out_path).read() != text:
    with open(out_path, "w", newline="\n") as f:
        f.write(text)
print("panel: %d files, %d bytes gzipped" % (len(entries), total))
