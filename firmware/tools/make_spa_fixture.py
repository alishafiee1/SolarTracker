"""Generate the NREL SPA reference tables for cycle 002 (R2, R5) with pvlib.

Usage: python firmware/tools/make_spa_fixture.py
Needs: pip install pvlib   (use a throwaway venv; it is not a firmware dependency)
Writes firmware/test/fixtures/spa_kerman.csv and spa_kerman.h (same data, for the host test).
"""
import os

import pandas as pd
import pvlib

LAT, LON = 30.283, 57.083  # Kerman
OUT = os.path.join(os.path.dirname(__file__), "..", "test", "fixtures")

# Four dates per year (equinoxes, solstices) x years 2026..2035 at hours covering sunrise to sunset,
# plus a few off-season dates, so the table spans all seasons and the whole range of years.
stamps = []
for year in range(2026, 2036):
    for month, day in ((3, 20), (6, 21), (9, 23), (12, 21)):
        for hour in (3, 6, 8, 10, 12, 14, 16, 18):  # UTC; local Iran time is UTC+3:30
            stamps.append(pd.Timestamp(year=year, month=month, day=day, hour=hour, minute=7, tz="UTC"))
for ts in ("2027-01-15 04:30", "2028-02-29 09:00", "2029-05-05 13:45", "2030-08-10 07:20", "2031-11-02 11:11"):
    stamps.append(pd.Timestamp(ts, tz="UTC"))

times = pd.DatetimeIndex(stamps)
sol = pvlib.solarposition.get_solarposition(times, LAT, LON, method="nrel_numpy")

rows = []
for ts, az, zen in zip(times, sol["azimuth"], sol["zenith"]):
    rows.append((int(ts.timestamp()), LAT, LON, float(az), float(zen)))

# Horizon crossings (zenith = 90 deg, geometric) per minute for 12 dates, used by the night-flag test (R5).
HORIZON_DAYS = ["2026-03-20", "2026-06-21", "2026-09-23", "2026-12-21", "2027-02-10", "2027-05-01",
                "2028-07-15", "2029-10-05", "2030-01-25", "2031-04-12", "2033-08-30", "2035-11-20"]
horizon = []
for day in HORIZON_DAYS:
    minutes = pd.date_range(day + " 00:00", periods=1440, freq="min", tz="UTC")
    z = pvlib.solarposition.get_solarposition(minutes, LAT, LON, method="nrel_numpy")["zenith"].to_numpy()
    up = [i for i in range(1, 1440) if z[i - 1] > 90.0 >= z[i]]
    down = [i for i in range(1, 1440) if z[i - 1] <= 90.0 < z[i]]
    assert len(up) == 1 and len(down) == 1, (day, up, down)
    start = int(minutes[0].timestamp())
    horizon.append((start, start + up[0] * 60, start + down[0] * 60))

os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "spa_kerman.csv"), "w", newline="\n") as f:
    f.write("utc_epoch,lat,lon,azimuth_deg,zenith_deg\n")
    for r in rows:
        f.write("%d,%.3f,%.3f,%.6f,%.6f\n" % r)

with open(os.path.join(OUT, "spa_kerman.h"), "w", newline="\n") as f:
    f.write("// Generated by firmware/tools/make_spa_fixture.py (pvlib %s, method nrel_numpy). Do not edit.\n" % pvlib.__version__)
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("struct SpaRow { int64_t utc; double lat; double lon; double azimuth; double zenith; };\n")
    f.write("static const SpaRow kSpaKerman[] = {\n")
    for r in rows:
        f.write("    {%dLL, %.3f, %.3f, %.6f, %.6f},\n" % r)
    f.write("};\n\n")
    f.write("// First minute with zenith <= 90 (sunrise) and first minute with zenith > 90 (sunset), UTC.\n")
    f.write("struct SpaHorizon { int64_t dayStartUtc; int64_t sunriseUtc; int64_t sunsetUtc; };\n")
    f.write("static const SpaHorizon kSpaHorizon[] = {\n")
    for h in horizon:
        f.write("    {%dLL, %dLL, %dLL},\n" % h)
    f.write("};\n")

print("rows:", len(rows), "horizon days:", len(horizon))
